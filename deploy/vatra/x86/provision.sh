#!/usr/bin/env bash
# Runs inside the Packer build VM (Debian 13 genericcloud amd64) as root.
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
cloud-init status --wait >/dev/null 2>&1 || true

# Docker from Docker's own repo (same as docker-debian-trixie in the Pi image)
install -d -m 0755 /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/debian/gpg -o /etc/apt/keyrings/docker.asc
chmod a+r /etc/apt/keyrings/docker.asc
echo "deb [arch=amd64 signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/debian trixie stable" \
  > /etc/apt/sources.list.d/docker.list
apt-get update -qq
# genericcloud ships linux-image-cloud-amd64 (virtio only): no e1000 (VirtualBox/OVA), vmxnet3
# (VMware), hv_netvsc (Hyper-V) or USB radios. A home appliance needs the generic kernel.
apt-get install -y -qq --no-install-recommends linux-image-amd64 >/dev/null
apt-get purge -y -qq 'linux-image-*-cloud-amd64' linux-image-cloud-amd64 >/dev/null 2>&1 || true
update-grub >/dev/null 2>&1 || true
apt-get install -y -qq --no-install-recommends docker-ce docker-ce-cli containerd.io docker-compose-plugin \
  avahi-daemon libnss-mdns python3 zstd curl ca-certificates cloud-guest-utils fdisk qemu-guest-agent >/dev/null

# payload: src/deploy/vatra, src/pi/avahi-vmui.service, bake/ (see build.sh)
rm -rf /tmp/vatra-src; mkdir -p /tmp/vatra-src
tar -xf /tmp/vatra-payload.tar -C /tmp/vatra-src
bash /tmp/vatra-src/src/deploy/vatra/hub-install.sh --root / --arch amd64 --bake /tmp/vatra-src/bake --platform x86
if [ "${VATRA_AB:-0}" = 1 ]; then
  bash /tmp/vatra-src/src/deploy/vatra/os/rootfs-ab.sh --platform x86 --version "${VATRA_VERSION:?}" --src /tmp/vatra-src/src
fi
systemctl enable qemu-guest-agent.service vatra-bootnote.service >/dev/null 2>&1 || true
# console shows the address + setup code (agetty reads /etc/issue.d)
install -d /etc/issue.d

# appliance identity: generic hostname until firstboot picks vatra-xxxx
echo vatra > /etc/hostname
sed -i 's/^127\.0\.1\.1.*/127.0.1.1\tvatra/' /etc/hosts

# networking without cloud-init: DHCP on any wired NIC through systemd-networkd
rm -f /etc/netplan/*cloud-init* /etc/network/interfaces.d/*cloud* 2>/dev/null || true
cat > /etc/systemd/network/80-vatra-wired.network <<'EOF'
[Match]
Name=en* eth*

[Network]
DHCP=yes
MulticastDNS=no
EOF
systemctl enable systemd-networkd.service >/dev/null 2>&1

# no build-time login survives: cloud-init goes now, the packer user at shutdown (Packer still
# needs it for this session), SSH host keys are regenerated by vatra-firstboot
install -m 0440 /dev/stdin /etc/sudoers.d/packer <<<'packer ALL=(ALL) NOPASSWD: ALL'
apt-get purge -y -qq cloud-init >/dev/null || true
rm -rf /etc/cloud /var/lib/cloud /etc/sudoers.d/90-cloud-init-users
rm -f /etc/ssh/ssh_host_*
apt-get clean
rm -rf /var/lib/apt/lists/* /tmp/vatra-* /root/.bash_history
truncate -s 0 /etc/machine-id
fstrim -av >/dev/null 2>&1 || true
echo "vatra x86 provisioned"
