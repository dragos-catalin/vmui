// Emit the mark geometry as a TS module for React consumers (web + desktop).
// node brand/scripts/emit-ts.mjs  -> src/components/brand/vatra-geometry.ts + apps/desktop/src/brand/vatra-geometry.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { geometry } from "./mark.mjs";

const g = Object.fromEntries(["master", "small", "micro"].map((s) => [s, geometry(s)]));
const body = `// GENERATED by brand/scripts/emit-ts.mjs from brand/scripts/mark.mjs — do not edit.
export type VatraOpticalSize = "master" | "small" | "micro";
export interface VatraGeometry {
  roof: string;
  walls: string;
  flame: string;
  core: string | null;
  puffs: ReadonlyArray<{ cx: number; cy: number; r: number }>;
  stroke: number;
  bbox: { x0: number; x1: number; y0: number; y1: number };
}
export const VATRA_GEOMETRY: Record<VatraOpticalSize, VatraGeometry> = ${JSON.stringify(
  Object.fromEntries(Object.entries(g).map(([k, v]) => [k, { roof: v.roof, walls: v.walls, flame: v.flame, core: v.core, puffs: v.puffs, stroke: v.stroke, bbox: v.bbox }])),
  null,
  2,
)};
export const opticalSizeFor = (px: number): VatraOpticalSize => (px <= 20 ? "micro" : px <= 48 ? "small" : "master");
`;
for (const dir of ["src/components/brand", "apps/desktop/src/brand"]) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(`${dir}/vatra-geometry.ts`, body);
}
console.log("emitted vatra-geometry.ts");
