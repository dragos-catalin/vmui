// Vatra logo motion: one parametric source (MOTION.logo + mark geometry classes) ->
//   brand/dist/css/vatra-motion.css   (consumed by web globals.css and desktop app.css)
//   brand/dist/motion/vatra-*.svg      (self-animating SVGs for README, docs, email-safe fallback = final frame)
//   brand/dist/motion/demo.html        (live demo of every state)
// States: intro, thinking (loader), success, error, hover/press, idle. Morph (splash -> UI) is done by
// the runtime (Motion layoutId on web, FLIP on desktop) using the same element classes.
// Static mark == final frame of every animation; prefers-reduced-motion disables all of it.
import { mkdirSync, writeFileSync } from "node:fs";
import { svg } from "./mark.mjs";
import { MOTION } from "./tokens.mjs";

const L = MOTION.logo;
const ease = (a) => `cubic-bezier(${a.join(", ")})`;
const out = MOTION.ease.out;
const inOut = MOTION.ease.inOut;

export const motionCss = `/* GENERATED by brand/scripts/motion.mjs — Vatra logo motion. Targets .vt-* classes emitted by mark.mjs. */
.vt-mark { overflow: visible; }
.vt-mark .vt-puff, .vt-mark .vt-flame, .vt-mark .vt-core { transform-box: fill-box; }
.vt-mark .vt-puff { transform-origin: center; }
.vt-mark .vt-flame, .vt-mark .vt-core { transform-origin: 50% 100%; }

/* thinking / loader: smoke rises (A · rising wisp), flame breathes */
@keyframes vt-rise { 0% { transform: translate(-6%, 30%) scale(0.6); opacity: 0 } 30% { opacity: 1 } 100% { transform: translate(8%, -40%) scale(1.15); opacity: 0 } }
@keyframes vt-breathe { 0%, 100% { transform: scale(1, 1) } 50% { transform: scale(0.93, 1.07) } }
.vt-mark[data-state="thinking"] .vt-puff { animation: vt-rise ${L.riseMs}ms ${ease([0.33, 0.7, 0.4, 1])} infinite both; }
.vt-mark[data-state="thinking"] .vt-p2 { animation-delay: ${L.stagger}ms; }
.vt-mark[data-state="thinking"] .vt-p3 { animation-delay: ${L.stagger * 2}ms; }
.vt-mark[data-state="thinking"] .vt-flame, .vt-mark[data-state="thinking"] .vt-core { animation: vt-breathe ${L.flameMs}ms ease-in-out infinite; }

/* idle: only the flame breathes, very slowly (opt-in; the static mark is the default) */
.vt-mark[data-state="idle"] .vt-flame, .vt-mark[data-state="idle"] .vt-core { animation: vt-breathe ${L.flameMs * 2}ms ease-in-out infinite; }

/* intro: roof draws, walls draw, flame ignites (overshoot), puffs pop in sequence */
@keyframes vt-draw { from { stroke-dashoffset: 101 } to { stroke-dashoffset: 0 } }
@keyframes vt-ignite { 0% { transform: scale(0); opacity: 0 } 60% { transform: scale(1.12, 1.18); opacity: 1 } 100% { transform: scale(1); opacity: 1 } }
@keyframes vt-pop { from { transform: translateY(40%) scale(0); opacity: 0 } to { transform: none; opacity: var(--vt-op, 1) } }
.vt-mark[data-state="intro"] .vt-roof, .vt-mark[data-state="intro"] .vt-walls { stroke-dasharray: 101 101; animation: vt-draw ${Math.round(L.introMs * 0.55)}ms ${ease(inOut)} both; }
.vt-mark[data-state="intro"] .vt-walls { animation-delay: ${Math.round(L.introMs * 0.12)}ms; }
.vt-mark[data-state="intro"] .vt-flame, .vt-mark[data-state="intro"] .vt-core { animation: vt-ignite ${Math.round(L.introMs * 0.32)}ms ${ease(out)} ${Math.round(L.introMs * 0.55)}ms both; }
.vt-mark[data-state="intro"] .vt-puff { animation: vt-pop 260ms ${ease(out)} both; }
.vt-mark[data-state="intro"] .vt-p1 { animation-delay: ${Math.round(L.introMs * 0.78)}ms; }
.vt-mark[data-state="intro"] .vt-p2 { animation-delay: ${Math.round(L.introMs * 0.86)}ms; }
.vt-mark[data-state="intro"] .vt-p3 { animation-delay: ${Math.round(L.introMs * 0.94)}ms; }

/* success: one big puff leaves, flame flares */
@keyframes vt-flare { 0%, 100% { transform: scale(1) } 40% { transform: scale(1.18, 1.28) } }
@keyframes vt-leave { 0% { transform: none; opacity: 1 } 55% { transform: translate(30%, -90%) scale(1.6); opacity: 0 } 56% { transform: translateY(40%) scale(0); opacity: 0 } 100% { transform: none; opacity: 1 } }
.vt-mark[data-state="success"] .vt-flame, .vt-mark[data-state="success"] .vt-core { animation: vt-flare 520ms ${ease(out)} both; }
.vt-mark[data-state="success"] .vt-puff { animation: vt-leave 1100ms ${ease(out)} both; }
.vt-mark[data-state="success"] .vt-p2 { animation-delay: 60ms; }
.vt-mark[data-state="success"] .vt-p3 { animation-delay: 120ms; }

/* error: smoke stops (fades), flame gutters to an ember */
@keyframes vt-gutter { 0% { transform: scale(1) } 30% { transform: scale(1.08, 0.8) } 100% { transform: scale(0.72, 0.6); opacity: 0.55 } }
.vt-mark[data-state="error"] .vt-flame, .vt-mark[data-state="error"] .vt-core { animation: vt-gutter 600ms ${ease(inOut)} both; }
.vt-mark[data-state="error"] .vt-puff { transition: opacity 300ms; opacity: 0.12; }

/* hover / press (interactive marks: sidebar brand, title bar) */
.vt-mark.vt-interactive { transition: transform ${MOTION.duration.fast}ms ${ease(out)}; }
.vt-mark.vt-interactive:hover .vt-puff { animation: vt-rise ${L.riseMs}ms ${ease([0.33, 0.7, 0.4, 1])} 1 both; }
.vt-mark.vt-interactive:hover .vt-p2 { animation-delay: ${Math.round(L.stagger * 0.5)}ms; }
.vt-mark.vt-interactive:hover .vt-p3 { animation-delay: ${L.stagger}ms; }
.vt-mark.vt-interactive:active { transform: scale(0.94); }

@media (prefers-reduced-motion: reduce) {
  .vt-mark *, .vt-mark { animation: none !important; transition: none !important; }
}
[data-motion="reduce"] .vt-mark *, [data-motion="reduce"] .vt-mark { animation: none !important; transition: none !important; }
`;

const anim = (state, way = "dark", size = "master", px = 160) =>
  svg({ size, way, px, classes: true }).replace("<svg ", `<svg class="vt-mark" data-state="${state}" `);
const selfAnimating = (state, way) => anim(state, way).replace("</svg>", `<style>${motionCss}</style></svg>`);

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}`) {
  mkdirSync("brand/dist/css", { recursive: true });
  mkdirSync("brand/dist/motion", { recursive: true });
  writeFileSync("brand/dist/css/vatra-motion.css", motionCss);
  for (const s of ["intro", "thinking", "success", "error", "idle"])
    for (const w of ["dark", "light"]) writeFileSync(`brand/dist/motion/vatra-${s}-${w}.svg`, selfAnimating(s, w));
  const demo = `<!doctype html><meta charset="utf-8"><title>Vatra logo motion</title><style>${motionCss}
body{margin:0;padding:24px;background:#120d0a;color:#efe6dc;font:13px system-ui;display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:18px}
.b{background:#1d1611;border-radius:18px;padding:28px 18px 14px;display:grid;justify-items:center;gap:10px}.b.l{background:#f4ede5;color:#2a1c14}
button{font:inherit;padding:6px 12px;border-radius:10px;border:1px solid #fff3;background:#2a211b;color:inherit}</style>
${["intro", "thinking", "success", "error", "idle"].map((s) => `<div class="b">${anim(s)}<div>${s}</div><button onclick="const m=this.parentNode.querySelector('svg');const s=m.dataset.state;m.dataset.state='';requestAnimationFrame(()=>m.dataset.state=s)">replay</button></div>`).join("")}
<div class="b">${anim("none").replace('class="vt-mark"', 'class="vt-mark vt-interactive"')}<div>hover / press</div></div>
${["thinking", "intro"].map((s) => `<div class="b l">${anim(s, "light")}<div>${s} · light</div></div>`).join("")}
<div class="b">${anim("thinking", "dark", "small", 32)}<div>thinking · 32 px (small)</div></div>`;
  writeFileSync("brand/dist/motion/demo.html", demo);
  console.log("motion ok");
}
