// Emit the brand tokens (brand/tokens/*.tokens.json, DTCG) as Kotlin for the native Android app.
// node brand/scripts/emit-compose.mjs          -> apps/android/ui/src/main/kotlin/ro/vatra/ui/VatraTokens.kt
// node brand/scripts/emit-compose.mjs --check  -> exit 1 when the committed file is stale (CI / tests)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COLOURWAYS, geometry, oklchToHex } from "./mark.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (f) => JSON.parse(readFileSync(join(root, "brand", "tokens", f), "utf8"));
const semantic = read("semantic.tokens.json");
const motion = read("motion.tokens.json");
const type = read("typography.tokens.json");

const camel = (k) => k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const argb = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;

function scheme(name) {
  const t = semantic.color[name];
  const fields = Object.entries(t).map(([k, v]) => `    ${camel(k)} = ${argb(v.$value.hex)},`);
  return `val ${name === "light" ? "VatraLight" : "VatraDark"} = VatraColors(\n${fields.join("\n")}\n)`;
}

const keys = Object.keys(semantic.color.light);
const dk = Object.keys(semantic.color.dark);
if (keys.join() !== dk.join()) throw new Error("light/dark token keys differ");

const dur = Object.entries(motion.duration).map(([k, v]) => `    const val ${camel(k)}Ms = ${v.$value.value}`);
const ease = Object.entries(motion.easing).map(([k, v]) => `    val ${camel(k)} = CubicBezierEasing(${v.$value.map((n) => `${n}f`).join(", ")})`);
const spring = Object.entries(motion.spring).map(
  ([k, v]) => `    val ${camel(k)} = VatraSpring(stiffness = ${v.$value.stiffness}f, damping = ${v.$value.damping}f, mass = ${v.$value.mass}f)`,
);
// rem -> dp at the web's 16 px root
const radius = Object.entries(type.radius).map(([k, v]) => `    val ${k} = ${v.$value.value * 16}.dp`);

const kstr = (s) => (s == null ? "null" : JSON.stringify(s));
const marks = ["master", "small", "micro"].map((size) => {
  const g = geometry(size);
  const puffs = g.puffs.map((p) => `VatraPuff(${p.cx}f, ${p.cy}f, ${p.r}f)`).join(", ");
  const b = g.bbox;
  return `    val ${size} = VatraMarkGeometry(\n        roof = ${kstr(g.roof)},\n        walls = ${kstr(g.walls)},\n        flame = ${kstr(g.flame)},\n        core = ${kstr(g.core)},\n        puffs = listOf(${puffs}),\n        stroke = ${g.stroke}f,\n        bbox = floatArrayOf(${b.x0}f, ${b.x1}f, ${b.y0}f, ${b.y1}f),\n    )`;
});

const out = `// GENERATED by brand/scripts/emit-compose.mjs from brand/tokens/*.tokens.json — do not edit.
package ro.vatra.ui

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

@Immutable
data class VatraColors(
${keys.map((k) => `    val ${camel(k)}: Color,`).join("\n")}
)

${scheme("light")}

${scheme("dark")}

/** Spring parameters as the web/desktop motion tokens give them (stiffness, damping, mass). */
@Immutable
data class VatraSpring(val stiffness: Float, val damping: Float, val mass: Float)

object VatraMotion {
${dur.join("\n")}
${ease.join("\n")}
${spring.join("\n")}
}

object VatraRadius {
${radius.join("\n")}
}

data class VatraPuff(val cx: Float, val cy: Float, val r: Float)

/** Mark geometry on the 48-unit keyline grid (brand/scripts/mark.mjs); bbox = x0, x1, y0, y1. */
class VatraMarkGeometry(
  val roof: String,
  val walls: String,
  val flame: String,
  val core: String?,
  val puffs: List<VatraPuff>,
  val stroke: Float,
  val bbox: FloatArray,
)

object VatraMarks {
${marks.join("\n")}
}
`;

// Adaptive launcher icon: the master mark centred in the 66 dp safe zone of a 108 dp canvas.
const hexOf = (c) => oklchToHex(...c);
function iconForeground(mono) {
  const g = geometry("master");
  const b = g.bbox;
  // 48 dp box: its diagonal (68 dp) just touches the 66 dp safe circle at the empty corners
  const k = 48 / Math.max(b.x1 - b.x0, b.y1 - b.y0);
  const tx = 54 - ((b.x0 + b.x1) / 2) * k;
  const ty = 54 - ((b.y0 + b.y1) / 2) * k;
  const w = COLOURWAYS.dark;
  const line = mono ? "#FFFFFFFF" : hexOf(w.line);
  const flame = mono ? "#FFFFFFFF" : hexOf(w.flame);
  const core = hexOf(w.core);
  const stroke = (d) => `    <path android:pathData="${d}" android:strokeColor="${line}" android:strokeWidth="${g.stroke}" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>`;
  const puffs = g.puffs.map((p, i) => {
    const d = `M${p.cx - p.r},${p.cy} a${p.r},${p.r} 0 1,0 ${p.r * 2},0 a${p.r},${p.r} 0 1,0 -${p.r * 2},0`;
    return `    <path android:pathData="${d}" android:fillColor="${line}" android:fillAlpha="${[0.95, 0.7, 0.45][i] ?? 0.45}"/>`;
  });
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by brand/scripts/emit-compose.mjs from brand/scripts/mark.mjs — do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <group android:translateX="${tx.toFixed(3)}" android:translateY="${ty.toFixed(3)}" android:scaleX="${k.toFixed(4)}" android:scaleY="${k.toFixed(4)}">
${stroke(g.roof)}
${stroke(g.walls)}
    <path android:pathData="${g.flame}" android:fillColor="${flame}"/>
${mono || !g.core ? "" : `    <path android:pathData="${g.core}" android:fillColor="${core}"/>\n`}${puffs.join("\n")}
  </group>
</vector>
`;
}
const background = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by brand/scripts/emit-compose.mjs — do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <path android:pathData="M0,0h108v108h-108z" android:fillColor="${hexOf(COLOURWAYS.dark.tile)}"/>
</vector>
`;
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@drawable/ic_launcher_background"/>
  <foreground android:drawable="@drawable/ic_launcher_foreground"/>
  <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
`;

const android = join(root, "apps", "android");

// Status-bar icon: micro optical size, white only (Android tints it), on a 24 dp canvas.
function smallIcon() {
  const g = geometry("micro");
  const b = g.bbox;
  const k = 22 / Math.max(b.x1 - b.x0, b.y1 - b.y0);
  const tx = 12 - ((b.x0 + b.x1) / 2) * k;
  const ty = 12 - ((b.y0 + b.y1) / 2) * k;
  const s = (d) => `    <path android:pathData="${d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="${g.stroke}" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>`;
  const puffs = g.puffs.map((p) => `    <path android:pathData="M${p.cx - p.r},${p.cy} a${p.r},${p.r} 0 1,0 ${p.r * 2},0 a${p.r},${p.r} 0 1,0 -${p.r * 2},0" android:fillColor="#FFFFFFFF"/>`);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by brand/scripts/emit-compose.mjs from brand/scripts/mark.mjs — do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
  <group android:translateX="${tx.toFixed(3)}" android:translateY="${ty.toFixed(3)}" android:scaleX="${k.toFixed(4)}" android:scaleY="${k.toFixed(4)}">
${s(g.roof)}
${s(g.walls)}
    <path android:pathData="${g.flame}" android:fillColor="#FFFFFFFF"/>
${puffs.join("\n")}
  </group>
</vector>
`;
}
const files = { [join(android, "ui", "src", "main", "kotlin", "ro", "vatra", "ui", "VatraTokens.kt")]: out };
for (const m of ["app", "wear", "tv"]) {
  const res = join(android, m, "src", "main", "res");
  files[join(res, "drawable", "ic_launcher_foreground.xml")] = iconForeground(false);
  files[join(res, "drawable", "ic_launcher_monochrome.xml")] = iconForeground(true);
  files[join(res, "drawable", "ic_launcher_background.xml")] = background;
  files[join(res, "mipmap-anydpi", "ic_launcher.xml")] = adaptive;
  files[join(res, "drawable", "ic_notification.xml")] = smallIcon();
}
// Google TV launcher banner 320x180 dp: dark tile, mark left; the wordmark is the app label under it.
{
  const g = geometry("master");
  const b = g.bbox;
  const k = 120 / Math.max(b.x1 - b.x0, b.y1 - b.y0);
  const tx = 160 - ((b.x0 + b.x1) / 2) * k;
  const ty = 90 - ((b.y0 + b.y1) / 2) * k;
  const w = COLOURWAYS.dark;
  const line = hexOf(w.line);
  const st = (d) => `    <path android:pathData="${d}" android:strokeColor="${line}" android:strokeWidth="${g.stroke}" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>`;
  files[join(android, "tv", "src", "main", "res", "drawable", "tv_banner.xml")] = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by brand/scripts/emit-compose.mjs — do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="320dp" android:height="180dp" android:viewportWidth="320" android:viewportHeight="180">
  <path android:pathData="M0,0h320v180h-320z" android:fillColor="${hexOf(w.tile)}"/>
  <group android:translateX="${tx.toFixed(3)}" android:translateY="${ty.toFixed(3)}" android:scaleX="${k.toFixed(4)}" android:scaleY="${k.toFixed(4)}">
${st(g.roof)}
${st(g.walls)}
    <path android:pathData="${g.flame}" android:fillColor="${hexOf(w.flame)}"/>
    <path android:pathData="${g.core}" android:fillColor="${hexOf(w.core)}"/>
  </group>
</vector>
`;
}

if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([f, body]) => {
    try {
      return readFileSync(f, "utf8").replace(/\r\n/g, "\n") !== body;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`stale (run node brand/scripts/emit-compose.mjs):\n${stale.map(([f]) => f).join("\n")}`);
    process.exit(1);
  }
  console.log("android brand outputs up to date");
} else {
  for (const [f, body] of Object.entries(files)) {
    mkdirSync(dirname(f), { recursive: true });
    writeFileSync(f, body);
  }
  console.log(`emitted ${Object.keys(files).length} files`);
}
