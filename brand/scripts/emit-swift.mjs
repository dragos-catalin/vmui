// Emit the brand tokens (brand/tokens/*.tokens.json, DTCG) as Swift for the native iOS / watchOS apps.
// node brand/scripts/emit-swift.mjs          -> apps/ios/VatraCore/Sources/VatraCore/VatraTokens.swift
// node brand/scripts/emit-swift.mjs --check  -> exit 1 when the committed file is stale (CI / tests)
// Colours are 0xRRGGBB; the SwiftUI layer (apps/ios/Vatra/Theme.swift) turns them into Color.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COLOURWAYS, geometry, oklchToHex } from "./mark.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (f) => JSON.parse(readFileSync(join(root, "brand", "tokens", f), "utf8"));
const semantic = read("semantic.tokens.json");
const motion = read("motion.tokens.json");
const type = read("typography.tokens.json");

const camel = (k) => k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const hex = (h) => `0x${h.slice(1).toUpperCase()}`;

const keys = Object.keys(semantic.color.light);
if (keys.join() !== Object.keys(semantic.color.dark).join()) throw new Error("light/dark token keys differ");
const scheme = (name) =>
  `  public static let ${name} = VatraPalette(\n${keys.map((k) => `    ${camel(k)}: ${hex(semantic.color[name][k].$value.hex)}`).join(",\n")}\n  )`;

const dur = Object.entries(motion.duration).map(([k, v]) => `  public static let ${camel(k)}: Double = ${v.$value.value / 1000}`);
const ease = Object.entries(motion.easing).map(([k, v]) => `  public static let ${camel(k) === "default" ? "standard" : camel(k)}: [Double] = [${v.$value.join(", ")}]`);
const spring = Object.entries(motion.spring).map(
  ([k, v]) => `  public static let ${camel(k) === "default" ? "standard" : camel(k)} = VatraSpring(stiffness: ${v.$value.stiffness}, damping: ${v.$value.damping}, mass: ${v.$value.mass})`,
);
const radius = Object.entries(type.radius).map(([k, v]) => `  public static let ${k}: Double = ${v.$value.value * 16}`);

const s = (v) => (v == null ? "nil" : JSON.stringify(v));
const marks = ["master", "small", "micro"].map((size) => {
  const g = geometry(size);
  const b = g.bbox;
  const puffs = g.puffs.map((p) => `VatraPuff(cx: ${p.cx}, cy: ${p.cy}, r: ${p.r})`).join(", ");
  return `  public static let ${size} = VatraMarkGeometry(\n    roof: ${s(g.roof)},\n    walls: ${s(g.walls)},\n    flame: ${s(g.flame)},\n    core: ${s(g.core)},\n    puffs: [${puffs}],\n    stroke: ${g.stroke},\n    bbox: [${b.x0}, ${b.x1}, ${b.y0}, ${b.y1}]\n  )`;
});
const way = (name) => {
  const w = COLOURWAYS[name];
  const h = (c) => (c ? hex(oklchToHex(...c)) : "nil");
  return `  public static let ${name} = VatraColourway(line: ${h(w.line)}, flame: ${h(w.flame)}, core: ${h(w.core)}, tile: ${h(w.tile)})`;
};

const out = `// GENERATED by brand/scripts/emit-swift.mjs from brand/tokens/*.tokens.json — do not edit.
// swiftlint:disable all

public struct VatraPalette: Sendable, Equatable {
${keys.map((k) => `  public let ${camel(k)}: UInt32`).join("\n")}

${scheme("light")}

${scheme("dark")}
}

/// Spring parameters as the web/desktop motion tokens give them (stiffness, damping, mass).
public struct VatraSpring: Sendable, Equatable {
  public let stiffness: Double
  public let damping: Double
  public let mass: Double
}

/// Durations in seconds; easings as cubic-bezier control points [x1, y1, x2, y2].
public enum VatraMotion {
${dur.join("\n")}
${ease.join("\n")}
${spring.join("\n")}
}

/// Corner radii in points (rem at the web's 16 px root).
public enum VatraRadius {
${radius.join("\n")}
}

public struct VatraPuff: Sendable, Equatable {
  public let cx: Double
  public let cy: Double
  public let r: Double
}

/// Mark geometry on the 48-unit keyline grid (brand/scripts/mark.mjs); bbox = x0, x1, y0, y1.
public struct VatraMarkGeometry: Sendable, Equatable {
  public let roof: String
  public let walls: String
  public let flame: String
  public let core: String?
  public let puffs: [VatraPuff]
  public let stroke: Double
  public let bbox: [Double]
}

public struct VatraColourway: Sendable, Equatable {
  public let line: UInt32
  public let flame: UInt32
  public let core: UInt32?
  public let tile: UInt32?

${way("dark")}
${way("light")}
${way("monoWhite")}
}

public enum VatraMarks {
${marks.join("\n")}

  /// The optical size the brand prescribes for a rendered size in points (brand/BRAND.md).
  public static func optical(for size: Double) -> VatraMarkGeometry {
    size <= 20 ? micro : size <= 48 ? small : master
  }
}
`;

const file = join(root, "apps", "ios", "VatraCore", "Sources", "VatraCore", "VatraTokens.swift");
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  } catch {}
  if (cur !== out) {
    console.error(`stale (run node brand/scripts/emit-swift.mjs): ${file}`);
    process.exit(1);
  }
  console.log("ios brand outputs up to date");
} else {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, out);
  console.log(`emitted ${file}`);
}
